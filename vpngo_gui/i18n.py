OVERRIDE = None  # "en-US" or "pt-BR" chosen in the settings menu; None follows the system.


def language():
    if OVERRIDE in MESSAGES:
        return OVERRIDE
    requested = os.environ.get("VPNGO_LANG") or os.environ.get("LC_ALL") or os.environ.get("LC_MESSAGES") \
        or os.environ.get("LANG") or (locale.getlocale()[0] or "")
    return "pt-BR" if requested.replace("_", "-").lower().startswith("pt") else "en-US"


def tr(message, /, **values):
    return MESSAGES[language()][message].format(**values)
